#!/usr/bin/env node
// Regenerates seed/content.json from the frontend's original content modules
// (my-portfolio-frontend/data/*.ts), so the database starts with exactly the site's existing content.
//
// Usage: npm run build-seed [-- --frontend ../my-portfolio-frontend]
// Requires the frontend's dependencies to be installed (it uses the frontend's TypeScript compiler).

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const args = process.argv.slice(2);
const frontendArg = args.includes("--frontend") ? args[args.indexOf("--frontend") + 1] : "../my-portfolio-frontend";
const frontendDir = path.resolve(__dirname, "..", frontendArg);
const dataDir = path.join(frontendDir, "data");
const outFile = path.resolve(__dirname, "../seed/content.json");

if (!fs.existsSync(dataDir)) {
  console.error(`Frontend data folder not found: ${dataDir}`);
  process.exit(1);
}

let ts;
try {
  ts = require(path.join(frontendDir, "node_modules/typescript"));
} catch {
  console.error("TypeScript not found in the frontend. Run `npm install` in my-portfolio-frontend first.");
  process.exit(1);
}

// Transpile every data module to CommonJS in a temp folder, then load the real runtime values.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "portfolio-seed-"));
for (const file of fs.readdirSync(dataDir).filter((f) => f.endsWith(".ts"))) {
  const source = fs.readFileSync(path.join(dataDir, file), "utf8");
  const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  if (/require\("@\//.test(output)) {
    console.error(`${file} imports another module at runtime via "@/"; only type imports are supported.`);
    process.exit(1);
  }
  fs.writeFileSync(path.join(tmp, file.replace(/\.ts$/, ".js")), output);
}

// The frontend reads NEXT_PUBLIC_SITE_URL in data/settings.ts; siteUrl is not stored in the database.
const load = (name) => require(path.join(tmp, `${name}.js`));
const { profile } = load("profile");
const { home } = load("home");
const { settings, socialLinks } = load("settings");
const { projects } = load("projects");
const { posts } = load("blog");
const { experience } = load("experience");
const { skillCategories, skills } = load("skills");
const { services } = load("services");
const { education, certifications } = load("education");
const { testimonials } = load("testimonials");
const { pageSeo } = load("seo");

// Drop undefined optional fields (JSON does that) and the env-derived siteUrl.
const plain = (value) => JSON.parse(JSON.stringify(value));
const { siteUrl: _siteUrl, ...storedSettings } = settings;

const content = {
  _source: "Generated by scripts/build-seed-from-frontend.js from my-portfolio-frontend/data/*.ts. Imported by `npm run seed` (insert-only).",
  profile: plain(profile),
  home: plain(home),
  settings: plain(storedSettings),
  socialLinks: plain(socialLinks),
  projects: plain(projects),
  posts: plain(posts),
  experience: plain(experience),
  skillCategories: plain(skillCategories),
  skills: plain(skills),
  services: plain(services),
  education: plain(education),
  certifications: plain(certifications),
  testimonials: plain(testimonials),
  seo: plain(pageSeo),
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${JSON.stringify(content, null, 2)}\n`);
fs.rmSync(tmp, { recursive: true, force: true });

console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
for (const [key, value] of Object.entries(content)) {
  if (key !== "_source") console.log(`  ${key.padEnd(16)} ${Array.isArray(value) ? `${value.length} records` : "1 document"}`);
}
